// Regenerate the precompiled manifest validator:
//   node scripts/generate-manifest-validator.mjs
// ajv compiles JSON schemas with `new Function`, which the production CSP
// (script-src without 'unsafe-eval') forbids. The runtime must therefore ship
// a build-time precompiled validator; never compile this schema in the app.
import Ajv2020 from 'ajv/dist/2020.js';
import standaloneCode from 'ajv/dist/standalone/index.js';
import {readFileSync, writeFileSync} from 'node:fs';
const schema = JSON.parse(readFileSync('src/lib/extensions/contracts/v2/manifest.schema.json', 'utf8'));
const ajv = new Ajv2020({allErrors: true, strict: false, code: {source: true, esm: true}});
const validate = ajv.compile(schema);
// ajv standalone leaves CJS require() calls for runtime helpers even in ESM mode;
// hoist them into real imports so the file loads in the browser and under tsx.
const toEsm = (code) => {
  const imports = [];
  let i = 0;
  const body = code.replace(/require\("ajv\/dist\/runtime\/([a-zA-Z0-9]+)"\)/g, (_, name) => {
    const local = `__ajvRuntime${i++}`;
    imports.push(`import ${local} from 'ajv/dist/runtime/${name}.js';`);
    return local;
  });
  return imports.join('\n') + '\n' + body;
};
const banner = '// GENERATED by scripts/generate-manifest-validator.mjs - do not edit by hand.\n// Regenerate after every manifest.schema.json change; the sync test enforces parity.\n';
writeFileSync('src/lib/extensions/contracts/v2/manifest.validator.js', banner + toEsm(standaloneCode(ajv, validate)));
console.log('manifest.validator.js regenerated');
