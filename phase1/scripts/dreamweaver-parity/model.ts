import type { Feature, Status } from './catalog';

/** Inputs the generator reads from the repo. Kept as plain data so the model is testable. */
export interface Inputs {
  /** ids from docs/ui-commands.json */
  commandIds: ReadonlySet<string>;
  /** registered studio ids */
  studioIds: ReadonlySet<string>;
  /** returns true if the repo-relative path exists */
  pathExists: (path: string) => boolean;
  /** returns true if the source file contains the quoted command id */
  sourceRegisters: (path: string, id: string) => boolean;
}

export interface Row {
  feature: Feature;
  status: Status;
  basis: 'registry' | 'manual';
  present: string[];
  absent: string[];
}

const rank: Record<Status, number> = { missing: 0, partial: 1, have: 2 };

export function evaluate(feature: Feature, inputs: Inputs): Row {
  const present: string[] = [];
  const absent: string[] = [];
  const check = (label: string, ok: boolean) => (ok ? present : absent).push(label);
  for (const id of feature.commands ?? []) check(`command ${id}`, inputs.commandIds.has(id));
  for (const r of feature.runtime ?? []) check(`runtime ${r.id}`, inputs.sourceRegisters(r.source, r.id));
  for (const id of feature.studios ?? []) check(`studio ${id}`, inputs.studioIds.has(id));
  for (const p of feature.evidence ?? []) check(`file ${p}`, inputs.pathExists(p));
  const total = present.length + absent.length;
  if (total === 0) {
    if (!feature.status) throw new Error(`Feature ${feature.id} has no requirements and no manual status`);
    return { feature, status: feature.status, basis: 'manual', present, absent };
  }
  const computed: Status = absent.length === 0 ? 'have' : present.length === 0 ? 'missing' : 'partial';
  const status = feature.status && rank[feature.status] < rank[computed] ? feature.status : computed;
  return { feature, status, basis: 'registry', present, absent };
}

export function validateCatalog(features: readonly Feature[]): string[] {
  const problems: string[] = [];
  const seen = new Set<string>();
  for (const f of features) {
    if (seen.has(f.id)) problems.push(`duplicate feature id ${f.id}`);
    seen.add(f.id);
    if (!/^[a-z]+\.[a-z-]+$/.test(f.id)) problems.push(`feature id ${f.id} must look like area.name`);
  }
  return problems;
}

const LABEL: Record<Status, string> = { have: 'Yes', partial: 'Partial', missing: 'No' };

export function render(rows: readonly Row[]): string {
  const count = (s: Status) => rows.filter(r => r.status === s).length;
  const areas = [...new Set(rows.map(r => r.feature.area))];
  const out: string[] = [
    '# Dreamweaver parity checklist',
    '',
    'Generated by `npm run inventory:dreamweaver-parity` from `phase1/scripts/dreamweaver-parity/catalog.ts`, `docs/ui-commands.json` and the studio registry. Do not edit by hand.',
    '`npm run check:dreamweaver-parity` fails CI when this file is out of date. Update the catalog, regenerate, and commit both.',
    '',
    'How to read it: a feature is **Yes** when everything the catalog requires for it exists (commands in the inventory, registered studios, source files). **Partial** means some of it exists, or the catalog caps it because the registry cannot prove full parity. **No** means nothing required exists. Rows with basis `manual` have no registry proof and carry a hand-set status.',
    '',
    `${rows.length} features: ${count('have')} yes, ${count('partial')} partial, ${count('missing')} no.`,
    '',
  ];
  for (const area of areas) {
    out.push(`## ${area}`, '', '| Feature | Dreamweaver | Somnia | Basis | Notes |', '| --- | --- | --- | --- | --- |');
    for (const r of rows.filter(x => x.feature.area === area)) {
      const gaps = r.absent.length ? `Missing: ${r.absent.map(a => `\`${a.replace(/^\w+ /, '')}\``).join(', ')}. ` : '';
      const note = `${gaps}${r.feature.note ?? ''}`.trim().replace(/\|/g, '\\|');
      out.push(`| ${r.feature.name} | ${r.feature.dreamweaver} | ${LABEL[r.status]} | ${r.basis} | ${note} |`);
    }
    out.push('');
  }
  return `${out.join('\n').replace(/\n+$/, '')}\n`;
}
