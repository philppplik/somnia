  await panel.getByRole('button',{name:'Agent configuration',exact:true}).click();
  await settings.getByLabel('Model',{exact:true}).fill('fixture-second');
  await settings.getByRole('button',{name:'Save AI settings',exact:true}).click();
  await settings.getByText('Configuration saved.',{exact:true}).waitFor();
  await settings.getByRole('button',{name:'Close settings',exact:true}).click();
  await panel.getByText('Fixture response',{exact:true}).waitFor();
  await panel.getByRole('button',{name:'Cloud data consent',exact:true}).click();
  assert.equal(await settings.getByRole('button',{name:'Allow cloud AI',exact:true}).isEnabled(),false);
  await settings.getByRole('tab',{name:'Providers & models',exact:true}).click();
  await settings.getByRole('combobox',{name:'Provider',exact:true}).selectOption('openrouter');
  await settings.getByRole('tab',{name:'Privacy & data',exact:true}).click();
  await settings.getByRole('checkbox',{name:/I agree/}).check();
  await settings.getByRole('button',{name:'Allow cloud AI',exact:true}).click();
  await settings.getByRole('tab',{name:'Providers & models',exact:true}).click();
