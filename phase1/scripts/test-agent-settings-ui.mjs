  await settings.getByRole('tab',{name:'Instructions',exact:true}).click();
  await settings.getByLabel('Prompt text 1',{exact:true}).fill('é'.repeat(4001));
  assert.equal(await settings.getByRole('button',{name:'Save AI settings',exact:true}).isEnabled(),false);
  await settings.getByLabel('Prompt text 1',{exact:true}).fill('Be concise');
  await page.screenshot({path:'/downloads/settings-ui/instructions.png'});
