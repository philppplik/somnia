import test from 'node:test';import assert from 'node:assert/strict';
import {registerHandoffRoute,handoffRoutesFor,setHandoffOrigin,handoffOrigin,clearHandoffOrigin,setPendingReturn,pendingReturnsFor,clearPendingReturn,handoffRefId,type StudioObjectRef} from './registry';
import {diffTableCells,tableToXlsx} from './slidesTable';
import {readXlsx} from '../office/xlsx';
const ref:StudioObjectRef={studio:'slides',kind:'table',id:'257:7',label:'Q3 numbers',file:'deck.pptx'};
test('routes register, query and unregister per studio:kind',()=>{const route={targetStudio:'sheets',titleKey:'handoff.editInSheets',open:async()=>{}};
 const off=registerHandoffRoute('slides','table',route);
 assert.deepEqual(handoffRoutesFor('slides','table'),[route]);
 assert.deepEqual(handoffRoutesFor('slides','picture'),[]);
 off();assert.deepEqual(handoffRoutesFor('slides','table'),[]);});
test('origins and pending returns are tracked per file and ref',()=>{setHandoffOrigin('Table.xlsx',ref);assert.equal(handoffOrigin('Table.xlsx'),ref);
 setPendingReturn('Table.xlsx',ref,[['a','b'],['1','2']]);
 assert.equal(pendingReturnsFor(handoffRefId(ref)).length,1);
 assert.equal(pendingReturnsFor('slides:picture:257:7').length,0);
 clearPendingReturn('Table.xlsx');assert.equal(pendingReturnsFor(handoffRefId(ref)).length,0);
 clearHandoffOrigin('Table.xlsx');assert.equal(handoffOrigin('Table.xlsx'),undefined);});
test('diffTableCells reports in-bounds edits and out-of-bounds growth',()=>{const current=[['a','b'],['1','2']];
 assert.deepEqual(diffTableCells(current,[['a','b'],['1','2']]),{edits:[],skippedRows:0,skippedCols:0});
 const d=diffTableCells(current,[['a','B'],['1','2','x'],['n','n']]);
 assert.deepEqual(d.edits,[{row:0,col:1,text:'B'}]);assert.equal(d.skippedRows,1);assert.equal(d.skippedCols,1);
 const capped=diffTableCells([['a']],[['b'],['c']],1);assert.equal(capped.edits.length,1);});
test('tableToXlsx round-trips through readXlsx with numbers typed',()=>{const bytes=tableToXlsx([['Name','Qty'],['Apples','3'],['Pie','2.5']],'Q3');
 const {sheets,warnings}=readXlsx(bytes);
 assert.equal(sheets.length,1);assert.equal(sheets[0].name,'Q3');
 assert.deepEqual(sheets[0].rows,[['Name','Qty'],['Apples',3],['Pie',2.5]]);
 assert.ok(Array.isArray(warnings));});
import {applyTableDiff,type TableEditTarget} from './applySlidesTableReturn';
test('applyTableDiff applies sequentially, waits for idle and stops on failure',async()=>{
 const calls:string[]=[];let idleAfter=0;
 const ok:TableEditTarget={busy:()=>idleAfter>0?idleAfter-- >0:false,editCell:async(r,c,text)=>{calls.push(`${r}:${c}:${text}`);return{ok:true};}};
 const d={edits:[{row:0,col:0,text:'a'},{row:1,col:1,text:'b'}],skippedRows:0,skippedCols:0};
 idleAfter=2;assert.deepEqual(await applyTableDiff(ok,d),{applied:2,total:2});
 assert.deepEqual(calls,['0:0:a','1:1:b']);
 const fail:TableEditTarget={busy:()=>false,editCell:async(r,c)=>({ok:r===0,message:'refused'})};
 const res=await applyTableDiff(fail,d);assert.equal(res.applied,1);assert.equal(res.failed,'refused');
 const stuck:TableEditTarget={busy:()=>true,editCell:async()=>({ok:true})};
 assert.equal((await applyTableDiff(stuck,d,120)).failed,'busy');});
