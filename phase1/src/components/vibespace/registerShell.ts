const AttentionPanel=lazyPanel(()=>import('./VibeSpacePanels').then(m=>m.AttentionPanel));
const MemoryShellPanel=lazyPanel(()=>import('./VibeSpacePanels').then(m=>m.MemoryShellPanel));
