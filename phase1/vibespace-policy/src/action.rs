//! Typed proposals and the vocabulary around them.

use crate::digest::ArgsDigest;
use crate::error::PolicyError;
use serde::{Deserialize, Serialize};
use std::collections::BTreeSet;
use std::fmt;

macro_rules! string_id {
    ($(#[$m:meta])* $name:ident, $what:literal) => {
        $(#[$m])*
        #[derive(Clone, Debug, PartialEq, Eq, Hash, PartialOrd, Ord, Serialize, Deserialize)]
        #[serde(try_from = "String", into = "String")]
        pub struct $name(String);

        impl $name {
            /// Validate and wrap (1..=128 chars of `A-Za-z0-9._:-`).
            pub fn new(value: impl Into<String>) -> Result<Self, PolicyError> {
                let value = value.into();
                let ok = !value.is_empty()
                    && value.len() <= 128
                    && value.bytes().all(|b| b.is_ascii_alphanumeric() || matches!(b, b'.' | b'_' | b':' | b'-'));
                if ok { Ok(Self(value)) } else { Err(PolicyError::InvalidId($what)) }
            }
            /// Borrow the id.
            pub fn as_str(&self) -> &str {
                &self.0
            }
        }
        impl TryFrom<String> for $name {
            type Error = PolicyError;
            fn try_from(v: String) -> Result<Self, PolicyError> {
                Self::new(v)
            }
        }
        impl From<$name> for String {
            fn from(v: $name) -> String {
                v.0
            }
        }
        impl fmt::Display for $name {
            fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
                f.write_str(&self.0)
            }
        }
    };
}

string_id!(
    /// Identifier of one run (owned by the Run-Manager).
    RunId, "run id"
);
string_id!(
    /// Identifier of the explicit scope a run operates in (for example the isolated copy).
    ScopeId, "scope id"
);
string_id!(
    /// Identifier of one proposal / consent request. Generated by the broker.
    ProposalId, "proposal id"
);
string_id!(
    /// Identifier of a run-level grant.
    GrantId, "grant id"
);

/// What an effect does. Shell, Network, Mcp and Desktop exist as proposal types so they can be
/// logged and denied; this crate has no enforcement for them (see `docs/vibespace/policy.md`).
#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash, PartialOrd, Ord, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum ActionKind {
    /// Read a file.
    Read,
    /// Create or replace a file.
    Write,
    /// Delete a file.
    Delete,
    /// Run a command.
    Shell,
    /// Tool network access (not model transport, see [`crate::transport`]).
    Network,
    /// MCP tool call.
    Mcp,
    /// Cross-app desktop control.
    Desktop,
}

impl ActionKind {
    /// Stable lowercase name.
    pub fn as_str(self) -> &'static str {
        match self {
            ActionKind::Read => "read",
            ActionKind::Write => "write",
            ActionKind::Delete => "delete",
            ActionKind::Shell => "shell",
            ActionKind::Network => "network",
            ActionKind::Mcp => "mcp",
            ActionKind::Desktop => "desktop",
        }
    }
}

/// High-impact categories that are always ask, never covered by autonomy, a run grant or a
/// skill's `allowed-tools`.
#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash, PartialOrd, Ord, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum HighImpact {
    /// Sends a message, mail or post to someone.
    Send,
    /// Buys something.
    Purchase,
    /// Touches credentials, keys or secrets.
    Credential,
    /// Touches payment details or moves money.
    Payment,
    /// Deletes data.
    Delete,
}

/// Trust tier of a skill (concept 4.4). It never grants anything; it is shown to the user.
#[derive(Clone, Copy, Debug, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum SkillTrust {
    /// Instructions only.
    Unreviewed,
    /// Automated checks passed.
    Scanned,
    /// Reviewed.
    Verified,
}

/// Who caused the proposal. Informational: no origin, including a Verified skill, changes what
/// is allowed.
#[derive(Clone, Debug, PartialEq, Eq, Serialize, Deserialize)]
#[serde(tag = "type", rename_all = "snake_case")]
pub enum Origin {
    /// The model's own tool call.
    Model,
    /// A tool call made while following a skill.
    Skill {
        /// Skill name.
        name: String,
        /// Trust tier.
        trust: SkillTrust,
    },
    /// An extension.
    Extension {
        /// Extension name.
        name: String,
    },
    /// A scheduled run.
    Schedule,
}

/// One requested effect. Built by tool code, never by the user and never accepted from model
/// text as an approval: a proposal only asks.
#[derive(Clone, Debug, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "camelCase", deny_unknown_fields)]
pub struct Proposal {
    /// Run the effect belongs to.
    pub run_id: RunId,
    /// Explicit scope the effect targets. Must equal the scope registered for the run.
    pub scope_id: ScopeId,
    /// Action type.
    pub kind: ActionKind,
    /// Canonical target (normalised relative path, host:port, tool name, ...).
    pub target: String,
    /// Why the agent wants it. Untrusted text, shown to the user after sanitising.
    pub reason: String,
    /// Digest of the exact arguments (see [`ArgsDigest`]).
    pub args_digest: ArgsDigest,
    /// Who caused it.
    pub origin: Origin,
    /// Impact categories declared by trusted tool metadata. Can only add restrictions.
    #[serde(default)]
    pub declared_impact: Vec<HighImpact>,
}

/// Autonomy level of a run. None of them bypass the hard boundaries.
#[derive(Clone, Copy, Debug, Default, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum Autonomy {
    /// Reads only. Writes are denied.
    ReadOnly,
    /// D5 default: reads in scope are allowed, writes ask.
    #[default]
    AskForWrites,
    /// Non-sensitive writes in the isolated copy are allowed without asking. Deletes, high-impact
    /// and credential-like targets still ask.
    AllowWritesInCopy,
}

/// Explicit scope of a run, registered by the host.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct RunScope {
    /// Run id.
    pub run_id: RunId,
    /// Scope id (for example the isolated copy's id).
    pub scope_id: ScopeId,
    /// Human label for the UI.
    pub label: String,
    /// Autonomy level.
    pub autonomy: Autonomy,
    /// Whether a person is watching. Unattended runs hold asks in the queue; nothing auto-allows.
    pub attended: bool,
    /// Action kinds the scope may use at all.
    pub allowed_kinds: BTreeSet<ActionKind>,
}

impl RunScope {
    /// D5 defaults: ask for writes, file kinds only.
    pub fn new(run_id: RunId, scope_id: ScopeId) -> Self {
        Self {
            run_id,
            scope_id,
            label: String::new(),
            autonomy: Autonomy::AskForWrites,
            attended: true,
            allowed_kinds: [ActionKind::Read, ActionKind::Write, ActionKind::Delete]
                .into_iter()
                .collect(),
        }
    }
}

/// What a human can answer.
#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum UserDecision {
    /// Refuse.
    Deny,
    /// Allow exactly this request, once.
    AllowOnce,
    /// Allow this action on this target for the rest of the run (revocable).
    AllowForRun,
}

/// The four policy outcomes.
#[derive(Clone, Copy, Debug, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum Decision {
    /// Waiting for the user.
    Ask,
    /// Refused.
    Deny,
    /// Allowed for one execution.
    AllowOnce,
    /// Allowed because of the run scope or a run grant.
    AllowForRun,
}
